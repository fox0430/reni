const MaxCodePoint = 0x0010FFFF'i32

proc isCodePoint*(r: Rune): bool {.inline.} =
  ## Whether ``r`` is a code point at all.  The subject is never validated, so
  ## ``fastRuneAt`` can decode a malformed sequence far above U+10FFFF, which
  ## every ``unicodedb`` lookup rejects with ``doAssert``.  Such a value is
  ## treated as unassigned and folds to itself.
  int32(r) >= 0'i32 and int32(r) <= MaxCodePoint

proc unicodeCategory(r: Rune): UnicodeCategory {.inline.} =
  if r.isCodePoint:
    properties.unicodeCategory(r)
  else:
    ctgCn

proc unicodeTypes(r: Rune): int {.inline.} =
  if r.isCodePoint:
    udbTypes.unicodeTypes(r)
  else:
    0

proc wordBreakProp(r: Rune): SgWord {.inline.} =
  if r.isCodePoint:
    segmentation.wordBreakProp(r)
  else:
    sgwOther

proc simpleCaseFold(r: Rune): Rune {.inline.} =
  if r.isCodePoint:
    casing.simpleCaseFold(r)
  else:
    r

iterator caseFoldVariants*(r: Rune): Rune =
  ## Every code point sharing ``r``'s simple case fold, ``r`` included.
  if r.isCodePoint:
    for variant in resolveCaseFold(r):
      yield variant
  else:
    yield r

proc inRangeTable*(cp: int32, table: openArray[(int32, int32)]): bool =
  ## Binary search a sorted table of (start, end) ranges.
  var lo = 0
  var hi = table.len - 1
  while lo <= hi:
    let mid = (lo + hi) div 2
    let (s, e) = table[mid]
    if cp < s:
      hi = mid - 1
    elif cp > e:
      lo = mid + 1
    else:
      return true
  return false

proc isOtherAlphabetic(r: Rune): bool {.inline.} =
  let cp = int32(r)
  # The table starts at U+0345, so everything below it (all of ASCII) is out.
  if cp < OtherAlphabeticRanges[0][0]:
    return false
  inRangeTable(cp, OtherAlphabeticRanges)

proc isAlphaChar*(r: Rune, cat: UnicodeCategory): bool {.inline.} =
  ## Oniguruma/POSIX Alpha: Unicode Alphabetic = L ∪ Nl ∪ Other_Alphabetic.
  ## Takes an already-resolved category to avoid a second lookup.
  cat in ctgL or cat == ctgNl or isOtherAlphabetic(r)

proc isAlphaChar*(r: Rune): bool {.inline.} =
  isAlphaChar(r, unicodeCategory(r))

proc isWordChar*(r: Rune, asciiOnly: bool, latin1Digits = true): bool {.inline.} =
  ## \w / Word: Alpha ∪ M ∪ Nd ∪ Pc ∪ six Latin-1 No digits (² ³ ¹ ¼ ½ ¾).
  ##
  ## Those six come from Oniguruma's ISO-8859-1 ctype override, which applies
  ## to a bare ``\w`` / ``\p{Word}`` only; ``[[:word:]]`` and any spelling
  ## inside ``[...]`` use the raw ``CR_Word`` ranges (``latin1Digits = false``).
  let c = int32(r)
  if c >= 0 and c < 128:
    return asciiHas(c, acWord)
  if asciiOnly:
    return false
  if latin1Digits and c < 0x0100 and (
    c == 0x00B2 or c == 0x00B3 or c == 0x00B9 or c == 0x00BC or c == 0x00BD or
    c == 0x00BE
  ):
    return true
  let cat = unicodeCategory(r)
  # Same set as Alpha ∪ M ∪ Nd ∪ Pc, but ordered so the Other_Alphabetic
  # range search stays the last resort instead of running for every M/Nd/Pc.
  cat in ctgL or cat in ctgM or cat == ctgNd or cat == ctgPc or cat == ctgNl or
    isOtherAlphabetic(r)

proc isDigitChar*(r: Rune, asciiOnly: bool): bool {.inline.} =
  ## \d: Decimal digit
  let c = int32(r)
  if c >= 0 and c < 128:
    return asciiHas(c, acDigit)
  if asciiOnly:
    return false
  unicodeCategory(r) == ctgNd

proc isSpaceChar*(r: Rune, asciiOnly: bool): bool {.inline.} =
  ## \s: Whitespace
  let c = int32(r)
  if c >= 0 and c < 128:
    return asciiHas(c, acSpace)
  if asciiOnly:
    return false
  let cat = unicodeCategory(r)
  cat in ctgZ or c == 0x85

proc isHexDigitChar*(r: Rune): bool {.inline.} =
  ## \h: Hex digit (always ASCII)
  let c = int32(r)
  asciiHas(c, acXdigit)

proc simpleFold*(r: Rune): Rune =
  ## Simple case fold for case-insensitive matching
  simpleCaseFold(r)

proc getMultiCharFold*(r: Rune): RuneBuf =
  ## The multi-character case fold expansion of ``r``, or ``len == 0`` when it
  ## has none.  Read straight out of [MultiCharFolds].
  if not hasMultiCharFold(r):
    return RuneBuf(runes: [Rune(0), Rune(0), Rune(0)], len: 0)
  let cp = int32(r)
  for f in MultiCharFolds:
    if f.source == cp:
      return RuneBuf(
        runes: [Rune(f.expansion[0]), Rune(f.expansion[1]), Rune(f.expansion[2])],
        len: f.len,
      )
  RuneBuf(runes: [Rune(0), Rune(0), Rune(0)], len: 0)

proc posixAsciiOnly*(cls: PosixClassName, flags: RegexFlags): bool =
  ## Check if POSIX class should use ASCII-only matching based on flags.
  ## (?P) implies all of them; (?W)/(?D)/(?S) only add the word/digit/space
  ## ctypes on top of it.
  if rfAsciiPosix in flags:
    return true
  case cls
  of pcWord:
    rfAsciiWord in flags
  of pcDigit:
    rfAsciiDigit in flags
  of pcSpace:
    rfAsciiSpace in flags
  else:
    # Oniguruma's ONIG_OPTION_WORD_IS_ASCII covers the WORD ctype only, so
    # (?W) must not narrow [[:alpha:]] / [[:alnum:]]; only (?P) does.
    false

proc matchPosixClass*(r: Rune, cls: PosixClassName, asciiOnly: bool): bool =
  let c = int32(r)
  if c >= 0 and c < 128:
    # ASCII: the table already agrees with both readings of every class.
    return
      case cls
      of pcAlnum:
        asciiHas(c, acAlnum)
      of pcAlpha:
        asciiHas(c, acAlpha)
      of pcAscii:
        true
      of pcBlank:
        asciiHas(c, acBlank)
      of pcCntrl:
        asciiHas(c, acCntrl)
      of pcDigit:
        asciiHas(c, acDigit)
      of pcGraph:
        asciiHas(c, acGraph)
      of pcLower:
        asciiHas(c, acLower)
      of pcPrint:
        asciiHas(c, acPrint)
      of pcPunct:
        asciiHas(c, acPunct)
      of pcSpace:
        asciiHas(c, acSpace)
      of pcUpper:
        asciiHas(c, acUpper)
      of pcXdigit:
        asciiHas(c, acXdigit)
      of pcWord:
        asciiHas(c, acWord)
  case cls
  of pcAlnum:
    if asciiOnly:
      (c >= ord('a') and c <= ord('z')) or (c >= ord('A') and c <= ord('Z')) or
        (c >= ord('0') and c <= ord('9'))
    else:
      # Alpha ∪ Nd
      let cat = unicodeCategory(r)
      isAlphaChar(r, cat) or cat == ctgNd
  of pcAlpha:
    if asciiOnly:
      (c >= ord('a') and c <= ord('z')) or (c >= ord('A') and c <= ord('Z'))
    else:
      isAlphaChar(r)
  of pcAscii:
    c >= 0 and c <= 127
  of pcBlank:
    if asciiOnly:
      c == 0x20 or c == 0x09
    else:
      # Zs ∪ {U+0009}
      c == 0x09 or unicodeCategory(r) == ctgZs
  of pcCntrl:
    if asciiOnly:
      (c >= 0 and c < 0x20) or c == 0x7F
    else:
      unicodeCategory(r) == ctgCc
  of pcDigit:
    if asciiOnly:
      c >= ord('0') and c <= ord('9')
    else:
      unicodeCategory(r) == ctgNd
  of pcGraph:
    if asciiOnly:
      c > 0x20 and c < 0x7F
    else:
      # category ∉ (Z + Cc + Cs + Cn); Cf and Co are graph.
      let cat = unicodeCategory(r)
      not (cat in (ctgZ + ctgCc + ctgCs + ctgCn))
  of pcLower:
    if asciiOnly:
      c >= ord('a') and c <= ord('z')
    else:
      # Same derived-property set as \p{Lower}: Ll plus Other_Lowercase.
      utmLowercase in unicodeTypes(r)
  of pcPrint:
    if asciiOnly:
      c >= 0x20 and c < 0x7F
    else:
      # category ∉ (Cc + Cs + Cn + Zl + Zp); Zs and Cf are print.
      let cat = unicodeCategory(r)
      not (cat in (ctgCc + ctgCs + ctgCn + ctgZl + ctgZp))
  of pcPunct:
    if asciiOnly:
      (c >= ord('!') and c <= ord('/')) or (c >= ord(':') and c <= ord('@')) or
        (c >= ord('[') and c <= ord('`')) or (c >= ord('{') and c <= ord('~'))
    else:
      # Oniguruma XPosixPunct = P ∪ S (marks, letters, numbers and the
      # separator/other categories are all excluded).
      let cat = unicodeCategory(r)
      not (cat in ctgL or cat in ctgN or cat in ctgZ or cat in ctgC or cat in ctgM)
  of pcSpace:
    isSpaceChar(r, asciiOnly)
  of pcUpper:
    if asciiOnly:
      c >= ord('A') and c <= ord('Z')
    else:
      # Same derived-property set as \p{Upper}: Lu plus Other_Uppercase.
      utmUppercase in unicodeTypes(r)
  of pcXdigit:
    isHexDigitChar(r)
  of pcWord:
    isWordChar(r, asciiOnly, latin1Digits = false)

