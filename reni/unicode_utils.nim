proc asciiRestricted(p: UniProp, flags: RegexFlags): bool {.inline.} =
  case p.restrict
  of uarNone:
    false
  of uarWord:
    rfAsciiWord in flags or rfAsciiPosix in flags
  of uarDigit:
    rfAsciiDigit in flags or rfAsciiPosix in flags
  of uarSpace:
    rfAsciiSpace in flags or rfAsciiPosix in flags
  of uarPosix:
    rfAsciiPosix in flags

proc matchUnicodeProp*(r: Rune, p: UniProp, flags: RegexFlags = {}): bool =
  ## Match a resolved ``\p{...}`` property.  See ``resolveUnicodeProp``.
  if asciiRestricted(p, flags):
    return matchPosixClass(r, p.restrictCls, true)
  case p.kind
  of upNever:
    false
  of upAlways:
    true
  of upCategory:
    unicodeCategory(r) in UnicodeCategorySet(p.catBits)
  of upTypeMask:
    UnicodeTypeMask(p.typeBits) in unicodeTypes(r)
  of upPosix:
    matchPosixClass(r, p.posixCls, false)
  of upWord:
    isWordChar(r, false)
  of upAscii:
    int32(r) >= 0 and int32(r) <= 127
  of upEmoji:
    inRangeTable(int32(r), EmojiRanges)
  of upExtPict:
    inRangeTable(int32(r), ExtPictRanges)
  of upBlock:
    int32(r) in blockRanges[int(p.blockIdx)]
  of upScript:
    r.isCodePoint and int(unicodeScript(r)) == int(p.scriptId)

proc graphemeBreakProp*(r: Rune): GcbProp =
  let cp = int32(r)
  # Single-value checks first
  if cp == 0x000D:
    return gcbCR
  if cp == 0x000A:
    return gcbLF
  if cp == 0x200D:
    return gcbZWJ
  # Control (CR and LF are excluded from the table by the checks above)
  if inRangeTable(cp, ControlRanges):
    return gcbControl
  # Regional Indicator
  if cp >= 0x1F1E6 and cp <= 0x1F1FF:
    return gcbRegionalIndicator
  # Hangul Jamo (Leading / Vowel / Trailing)
  if inRangeTable(cp, HangulLRanges):
    return gcbL
  if inRangeTable(cp, HangulVRanges):
    return gcbV
  if inRangeTable(cp, HangulTRanges):
    return gcbT
  # Hangul Syllable (LV or LVT)
  if cp >= HangulSBase and cp < HangulSBase + HangulSCount:
    if (cp - HangulSBase) mod HangulTCount == 0:
      return gcbLV
    else:
      return gcbLVT
  # Prepend
  if inRangeTable(cp, PrependRanges):
    return gcbPrepend
  # SpacingMark: the table is the exact GCB=SpacingMark set, which also
  # covers U+0E33 and U+0EB3 (General_Category Lo, not Mc).
  if inRangeTable(cp, SpacingMarkRanges):
    return gcbSpacingMark
  # Extend: the table is the exact GCB=Extend set, so no general-category
  # fallback is needed - every Cf that is not Extend is Control or Prepend.
  if inRangeTable(cp, ExtendRanges):
    return gcbExtend
  gcbOther

proc nextCharAt*(s: openArray[char], p: var int, r: var Rune) {.inline.} =
  ## Decode the character at ``p`` and advance past it, under the same length
  ## rule the matcher and the scan loops use.  A sequence truncated by the end
  ## of ``s`` is not a character, so its lead byte stands for itself; the
  ## segmentation algorithms below only need to keep making progress there.
  var code: int32
  var np: int
  if decodeAt(s, p, code, np):
    r = Rune(code)
    p = np
  else:
    r = Rune(int32(s[p].uint8))
    inc p

proc isGraphemeBoundary*(subject: openArray[char], pos: int): bool =
  ## Determine if there is a grapheme cluster boundary at byte position `pos`
  ## in `subject`. Returns true at string boundaries and at grapheme breaks.
  ## Implements UAX #29 grapheme cluster boundary rules (simplified).
  if pos <= 0 or pos >= subject.len:
    return true
  # Decode the rune just before pos and at pos
  var prevStart: int
  let prevRune = Rune(prevCharAt(subject, pos, prevStart))
  var curPos = pos
  var curRune: Rune
  if curPos < subject.len:
    nextCharAt(subject, curPos, curRune)
  else:
    return true
  let prev = graphemeBreakProp(prevRune)
  let cur = graphemeBreakProp(curRune)
  # GB3: Do not break between CR and LF
  if prev == gcbCR and cur == gcbLF:
    return false
  # GB4: Break after controls
  if prev in {gcbControl, gcbCR, gcbLF}:
    return true
  # GB5: Break before controls
  if cur in {gcbControl, gcbCR, gcbLF}:
    return true
  # GB6: Do not break Hangul syllable sequences (L × (L | V | LV | LVT))
  if prev == gcbL and cur in {gcbL, gcbV, gcbLV, gcbLVT}:
    return false
  # GB7: (LV | V) × (V | T)
  if prev in {gcbLV, gcbV} and cur in {gcbV, gcbT}:
    return false
  # GB8: (LVT | T) × T
  if prev in {gcbLVT, gcbT} and cur == gcbT:
    return false
  # GB9: × (Extend | ZWJ)
  if cur in {gcbExtend, gcbZWJ}:
    return false
  # GB9a: × SpacingMark
  if cur == gcbSpacingMark:
    return false
  # GB9b: Prepend ×
  if prev == gcbPrepend:
    return false
  # GB11: \p{Extended_Pictographic} Extend* ZWJ × \p{Extended_Pictographic}
  if prev == gcbZWJ and inRangeTable(int32(curRune), ExtPictRanges):
    # Check that before the ZWJ there is ExtPict followed by zero or more Extends
    var scanPos = prevStart
    while scanPos > 0:
      var sp: int
      let r2 = Rune(prevCharAt(subject, scanPos, sp))
      let prop = graphemeBreakProp(r2)
      if prop == gcbExtend:
        scanPos = sp
        continue
      if inRangeTable(int32(r2), ExtPictRanges):
        return false # GB11 applies
      break
    # GB11 does not apply if no ExtPict found before ZWJ
  # GB12/GB13: Regional_Indicator handling (pairs)
  if prev == gcbRegionalIndicator and cur == gcbRegionalIndicator:
    # Count preceding RI characters
    var riCount = 0
    var scanPos = prevStart
    while scanPos > 0:
      var sp: int
      let r2 = Rune(prevCharAt(subject, scanPos, sp))
      if graphemeBreakProp(r2) != gcbRegionalIndicator:
        break
      inc riCount
      scanPos = sp
    # Don't break if odd number of RI before (makes a pair)
    if riCount mod 2 == 0:
      return false
    return true
  # GB999: Otherwise, break
  true

proc nextGraphemeClusterEnd*(subject: openArray[char], pos: int): int =
  ## Return the byte position just past the end of the grapheme cluster
  ## starting at `pos`.
  if pos >= subject.len:
    return pos
  var p = pos
  var r: Rune
  nextCharAt(subject, p, r)
  # Consume following characters that don't form a boundary
  while p < subject.len:
    if isGraphemeBoundary(subject, p):
      break
    nextCharAt(subject, p, r)
  p

const
  # Word_Break=ALetter or Hebrew_Letter (AHLetter in UAX #29).  unicodedb
  # folds the code points that are both ALetter and Extended_Pictographic into
  # one value: they count as letters here, while WB3c asks ExtPictRanges the
  # way Oniguruma consults Extended_Pictographic directly.
  AHLetterProps = {sgwAletter, sgwHebrewLetter, sgwAletterExtendedPictographic}

proc isWordBoundaryUax29*(subject: openArray[char], pos: int): bool =
  ## Determine if there is a word boundary at byte position `pos`
  ## per UAX #29 word break rules. Returns true at string boundaries.
  if pos <= 0 or pos >= subject.len:
    return true
  # Decode runes before and at pos
  var prevStart: int
  let prevRune = Rune(prevCharAt(subject, pos, prevStart))
  var curPos = pos
  var curRune: Rune
  nextCharAt(subject, curPos, curRune)
  let prev = wordBreakProp(prevRune)
  let cur = wordBreakProp(curRune)
  # WB3: Do not break between CR and LF
  if prev == sgwCr and cur == sgwLf:
    return false
  # WB3a/WB3b: Break after/before newlines
  if prev in {sgwCr, sgwLf, sgwNewline}:
    return true
  if cur in {sgwCr, sgwLf, sgwNewline}:
    return true
  # WB3c: ZWJ × \p{Extended_Pictographic}
  if prev == sgwZwj and inRangeTable(int32(curRune), ExtPictRanges):
    return false
  # WB3d: WSegSpace × WSegSpace
  if prev == sgwWsegSpace and cur == sgwWsegSpace:
    return false
  # WB4: Skip Extend/Format/ZWJ (treat as transparent)
  # Get the "effective" previous property (skip Extend/Format/ZWJ)
  var effPrev = prev
  var effPrevRune = prevRune
  # Where ``effPrevRune`` starts.  The look-back loops below must scan from
  # here, not from ``prevStart``: when WB4 skipped an Extend/Format/ZWJ run,
  # stepping back from ``prevStart`` lands on ``effPrevRune`` itself.
  var effPrevStart = prevStart
  if effPrev in {sgwExtend, sgwFormat, sgwZwj}:
    var sp = prevStart
    while sp > 0:
      var sp2: int
      let r2 = Rune(prevCharAt(subject, sp, sp2))
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        effPrev = p2
        effPrevRune = r2
        effPrevStart = sp2
        break
      sp = sp2
  # WB5: AHLetter × AHLetter
  let isAHPrev = effPrev in AHLetterProps
  let isAHCur = cur in AHLetterProps
  if isAHPrev and isAHCur:
    return false
  # WB6: AHLetter × (MidLetter | MidNumLetQ) AHLetter
  if isAHPrev and cur in {sgwMidLetter, sgwMidNumLet, sgwSingleQuote}:
    # Look ahead: is the char after cur an AHLetter?
    var np = curPos
    # Skip the current char (already consumed by fastRuneAt above)
    # Skip Extend/Format/ZWJ
    while np < subject.len:
      var r2: Rune
      var np2 = np
      nextCharAt(subject, np2, r2)
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 in AHLetterProps:
          return false
        break
      np = np2
  # WB7: AHLetter (MidLetter | MidNumLetQ) × AHLetter
  if isAHCur and effPrev in {sgwMidLetter, sgwMidNumLet, sgwSingleQuote}:
    # Look back further: is the char before effPrev an AHLetter?
    var sp = effPrevStart
    while sp > 0:
      var sp2: int
      let r2 = Rune(prevCharAt(subject, sp, sp2))
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 in AHLetterProps:
          return false
        break
      sp = sp2
  # WB7a: Hebrew_Letter × Single_Quote
  if effPrev == sgwHebrewLetter and cur == sgwSingleQuote:
    return false
  # WB7b: Hebrew_Letter × Double_Quote Hebrew_Letter
  if effPrev == sgwHebrewLetter and cur == sgwDoubleQuote:
    var np = curPos
    while np < subject.len:
      var r2: Rune
      var np2 = np
      nextCharAt(subject, np2, r2)
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 == sgwHebrewLetter:
          return false
        break
      np = np2
  # WB7c: Hebrew_Letter Double_Quote × Hebrew_Letter
  if cur == sgwHebrewLetter and effPrev == sgwDoubleQuote:
    var sp = effPrevStart
    while sp > 0:
      var sp2: int
      let r2 = Rune(prevCharAt(subject, sp, sp2))
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 == sgwHebrewLetter:
          return false
        break
      sp = sp2
  # WB8: Numeric × Numeric
  if effPrev == sgwNumeric and cur == sgwNumeric:
    return false
  # WB9: AHLetter × Numeric
  if isAHPrev and cur == sgwNumeric:
    return false
  # WB10: Numeric × AHLetter
  if effPrev == sgwNumeric and isAHCur:
    return false
  # WB11: Numeric (MidNum | MidNumLetQ) × Numeric
  if cur == sgwNumeric and effPrev in {sgwMidNum, sgwMidNumLet, sgwSingleQuote}:
    var sp = effPrevStart
    while sp > 0:
      var sp2: int
      let r2 = Rune(prevCharAt(subject, sp, sp2))
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 == sgwNumeric:
          return false
        break
      sp = sp2
  # WB12: Numeric × (MidNum | MidNumLetQ) Numeric
  if effPrev == sgwNumeric and cur in {sgwMidNum, sgwMidNumLet, sgwSingleQuote}:
    var np = curPos
    while np < subject.len:
      var r2: Rune
      var np2 = np
      nextCharAt(subject, np2, r2)
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 == sgwNumeric:
          return false
        break
      np = np2
  # WB13: Katakana × Katakana
  if effPrev == sgwKatakana and cur == sgwKatakana:
    return false
  # WB13a: (AHLetter | Numeric | Katakana | ExtendNumLet) × ExtendNumLet
  if cur == sgwExtendNumLet and
      effPrev in AHLetterProps + {sgwNumeric, sgwKatakana, sgwExtendNumLet}:
    return false
  # WB13b: ExtendNumLet × (AHLetter | Numeric | Katakana)
  if effPrev == sgwExtendNumLet and cur in AHLetterProps + {sgwNumeric, sgwKatakana}:
    return false
  # WB15/WB16: Regional Indicator handling (pairs)
  if effPrev == sgwRegionalIndicator and cur == sgwRegionalIndicator:
    var riCount = 0
    var sp = effPrevStart
    while sp > 0:
      var sp2: int
      let r2 = Rune(prevCharAt(subject, sp, sp2))
      let p2 = wordBreakProp(r2)
      if p2 notin {sgwExtend, sgwFormat, sgwZwj}:
        if p2 != sgwRegionalIndicator:
          break
        inc riCount
      sp = sp2
    if riCount mod 2 == 0:
      return false
    return true
  # WB4: × (Extend | Format | ZWJ)
  if cur in {sgwExtend, sgwFormat, sgwZwj}:
    return false
  # WB999: Otherwise, break
  return true

proc nextWordSegmentEnd*(subject: openArray[char], pos: int): int =
  ## Return the byte position just past the end of the word segment
  ## starting at `pos` (per UAX #29 word boundaries).
  if pos >= subject.len:
    return pos
  var p = pos
  var r: Rune
  nextCharAt(subject, p, r)
  while p < subject.len:
    if isWordBoundaryUax29(subject, p):
      break
    nextCharAt(subject, p, r)
  return p

proc caseInsensitiveMatch*(r, target: Rune, flags: RegexFlags): bool =
  ## Case-insensitive comparison respecting rfIgnoreCaseAscii flag.
  if rfIgnoreCase notin flags:
    return r == target
  if rfIgnoreCaseAscii in flags:
    # ASCII-only: only fold if both are ASCII
    if int32(r) <= 127 and int32(target) <= 127:
      return simpleFold(r) == simpleFold(target)
    return r == target
  simpleFold(r) == simpleFold(target)

proc matchCcAtom*(r: Rune, atom: CcAtom, flags: RegexFlags): bool =
  case atom.kind
  of ccLiteral:
    r == atom.rune or caseInsensitiveMatch(r, atom.rune, flags)
  of ccRange:
    let lo = int32(atom.rangeFrom)
    let hi = int32(atom.rangeTo)
    let ri = int32(r)
    if ri >= lo and ri <= hi:
      true
    elif rfIgnoreCase in flags:
      if rfIgnoreCaseAscii in flags:
        # ASCII-only: the subject and the variant it folds to must both be
        # ASCII, so ``k`` never reaches U+212A and U+212A never reaches ``k``.
        #
        # Walk the variants rather than folding once.  A range is not a value
        # that can be folded alongside the subject the way [caseInsensitiveMatch]
        # folds both sides of a literal, and ``simpleFold`` maps toward one
        # case only -- testing it against the range's own endpoints answers
        # only for a range written in that case, so ``[a-z]`` would match ``Y``
        # while ``[A-Z]`` missed ``y``.
        if ri <= 127:
          for variant in caseFoldVariants(r):
            let vi = int32(variant)
            if vi <= 127 and vi >= lo and vi <= hi:
              return true
          false
        else:
          false
      else:
        # Check if any case variant of r falls in the original range
        for variant in caseFoldVariants(r):
          if int32(variant) >= lo and int32(variant) <= hi:
            return true
        false
    else:
      false
  of ccCharType:
    case atom.charType
    of ctWord:
      # Inside [...] Oniguruma uses the raw CR_Word ranges: no Latin-1 extras.
      isWordChar(r, rfAsciiWord in flags or rfAsciiPosix in flags, latin1Digits = false)
    of ctNotWord:
      not isWordChar(
        r, rfAsciiWord in flags or rfAsciiPosix in flags, latin1Digits = false
      )
    of ctDigit:
      isDigitChar(r, rfAsciiDigit in flags or rfAsciiPosix in flags)
    of ctNotDigit:
      not isDigitChar(r, rfAsciiDigit in flags or rfAsciiPosix in flags)
    of ctSpace:
      isSpaceChar(r, rfAsciiSpace in flags or rfAsciiPosix in flags)
    of ctNotSpace:
      not isSpaceChar(r, rfAsciiSpace in flags or rfAsciiPosix in flags)
    of ctHexDigit:
      isHexDigitChar(r)
    of ctNotHexDigit:
      not isHexDigitChar(r)
    of ctDot, ctAnyChar:
      true
    of ctNotNewline:
      r != Rune(0x0A)
    of ctNewlineSeq:
      let c = int32(r)
      c == 0x0A or c == 0x0D or c == 0x0B or c == 0x0C or c == 0x85 or c == 0x2028 or
        c == 0x2029
    of ctGraphemeCluster:
      true # \X in character classes: any character
  of ccPosix:
    matchPosixClass(r, atom.posixClass, posixAsciiOnly(atom.posixClass, flags))
  of ccNegPosix:
    not matchPosixClass(r, atom.posixClass, posixAsciiOnly(atom.posixClass, flags))
  of ccUnicodeProp:
    matchUnicodeProp(r, atom.prop, flags)
  of ccNegUnicodeProp:
    not matchUnicodeProp(r, atom.prop, flags)
  of ccNestedClass:
    var anyMatch = false
    for nested in atom.nestedAtoms:
      if matchCcAtom(r, nested, flags):
        anyMatch = true
        break
    if atom.nestedNegated:
      not anyMatch
    else:
      anyMatch
  of ccIntersection:
    # Character must match BOTH left and right sides
    var leftMatch = false
    for a in atom.interLeft:
      if matchCcAtom(r, a, flags):
        leftMatch = true
        break
    if atom.interLeftNeg:
      leftMatch = not leftMatch
    var rightMatch = false
    for a in atom.interRight:
      if matchCcAtom(r, a, flags):
        rightMatch = true
        break
    if atom.interRightNeg:
      rightMatch = not rightMatch
    leftMatch and rightMatch

const AsciiRestrictFlags = {rfAsciiWord, rfAsciiDigit, rfAsciiSpace, rfAsciiPosix}
  ## The flags a class atom can read below U+0080.  Each only ever turns some
  ## test's ``asciiOnly`` argument on (``posixAsciiOnly`` and
  ## ``asciiRestricted`` are disjunctions over this set), so all four set and
  ## none set are the two extremes: an atom that answers the same at both ends
  ## answers the same for every combination in between.  ``rfIgnoreCase`` is
  ## out of reach here, since the matcher gates the bitset on its absence.

proc atomAsciiFlagInvariant(atom: CcAtom): bool =
  ## Whether ``atom`` reads every ASCII code point the same however the
  ## ASCII-restriction flags are set.
  ##
  ## Only a ``\p{...}`` can answer no.  Every other atom settles its ASCII
  ## answer before the flags are consulted: ``ccLiteral`` and ``ccRange`` never
  ## read one, and ``matchPosixClass`` / ``isWordChar`` / ``isDigitChar`` /
  ## ``isSpaceChar`` return from their ASCII tables above ``asciiOnly``.  A
  ## restriction does not narrow a property, it swaps it for ``restrictCls``,
  ## and nothing makes those two agree below U+0080.
  ##
  ## Today they do agree, so this probe rejects no atom and no test exercises
  ## a rejection; it is here for the pairing that stops agreeing (a table
  ## regenerated against a newer Unicode, or a ``restrictCls`` pointed at a
  ## ctype that differs in the ASCII range).  Composites are checked child by
  ## child: checking only the whole could miss two children that cancel at
  ## both ends and disagree in between.
  case atom.kind
  of ccNestedClass:
    for nested in atom.nestedAtoms:
      if not atomAsciiFlagInvariant(nested):
        return false
    true
  of ccIntersection:
    for a in atom.interLeft:
      if not atomAsciiFlagInvariant(a):
        return false
    for a in atom.interRight:
      if not atomAsciiFlagInvariant(a):
        return false
    true
  of ccUnicodeProp, ccNegUnicodeProp:
    if atom.prop.restrict == uarNone:
      return true
    for cp in 0'i32 .. 127'i32:
      let r = Rune(cp)
      if matchCcAtom(r, atom, {}) != matchCcAtom(r, atom, AsciiRestrictFlags):
        return false
    true
  else:
    true

proc exactAsciiClassSet*(atoms: seq[CcAtom], s: var set[uint8]): bool =
  ## The ASCII bytes ``atoms`` match, *before* negation, or false when that
  ## set is not exact.  Each byte is asked of the atoms themselves rather than
  ## derived from their shape, so a ``\p{...}``, a nested class and an
  ## intersection answer here too -- which the shape-reading
  ## [classAsciiMatches] cannot do, hence this fallback.  A class an
  ## ASCII-restriction flag can move gives up instead: those flags are
  ## switched on inside the pattern, and no compile-time set stands for both
  ## readings.
  for atom in atoms:
    if not atomAsciiFlagInvariant(atom):
      return false
  s = {}
  for cp in 0'i32 .. 127'i32:
    let r = Rune(cp)
    for atom in atoms:
      if matchCcAtom(r, atom, {}):
        s.incl(uint8(cp))
        break
  true
